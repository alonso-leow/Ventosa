#!/usr/bin/env python3
"""Build recording/clips.json + index.md from videos/*.md beat tables.
One clip per beat that has narration. Re-running keeps status, takes, edited text.
"""
import json, re, pathlib, datetime
import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from ws import ROOT, SUBJECTS  # noqa: E402
OUT = ROOT / "recording"
old = {}
if (OUT / "clips.json").exists():
    old = json.loads((OUT / "clips.json").read_text())
data = {"videos": {}, "updated": ""}
for f in sorted(SUBJECTS.glob("*.md")):
    txt = f.read_text()
    fm = re.match(r"^---\n(.*?)\n---\n", txt, re.S)
    meta = dict(l.split(":", 1) for l in fm.group(1).splitlines() if ":" in l) if fm else {}
    vid = meta.get("id", "").strip()
    title = meta.get("title", "").strip().strip('"')
    cols, lines = None, []
    for row in txt.splitlines():
        if not row.startswith("|"):
            continue
        cells = [c.strip() for c in row.strip().strip("|").split("|")]
        if cells and cells[0] == "id":
            cols = ["narration" if c.lower().startswith("narration") else c.lower() for c in cells]; continue
        if cols is None or set(row) <= set("|-: ") or len(cells) != len(cols):
            continue
        r = dict(zip(cols, cells))
        narr = r.get("narration", "")
        if not narr:
            continue
        lines.append({"id": f"{vid}-{r['id']}", "beat": r["id"], "t": r.get("t", ""), "act": r.get("act", ""),
                      "source": r.get("source", ""), "text": narr, "script_text": narr, "reel": r.get("reel", ""),
                      "status": "pending", "take": 1, "takes": [], "decision": ""})
    prev = {l["id"]: l for l in old.get("videos", {}).get(vid, {}).get("lines", [])}
    merged = []
    for l in lines:
        p = prev.pop(l["id"], None)
        if p:
            # keep recording state; refresh script_text; keep user edit unless untouched
            if p.get("text") == p.get("script_text"):
                p["text"] = l["text"]
            p["script_text"] = l["text"]
            for k in ("t", "act", "source", "reel"):
                p[k] = l[k]
            l = p
        merged.append(l)
    merged += [p for p in prev.values() if p.get("extra")]  # user-added lines survive
    data["videos"][vid] = {"title": title, "file": str(f.relative_to(ROOT)), "script_status": meta.get("status", "").strip(), "lines": merged}
data["updated"] = datetime.datetime.now().isoformat(timespec="seconds")
(OUT / "clips.json").write_text(json.dumps(data, indent=1, ensure_ascii=False))

md = ["# Clip index (generated by `build_index.py`, state edited by the teleprompter)\n",
      "Status: `pending` · `recorded` · `discarded` · `reshoot` (auto-queued after a discard).\n"]
tot = {}
for vid, v in data["videos"].items():
    md.append(f"\n## {vid} · {v['title']}  \n[script]({'../' + v['file']})\n")
    md.append("| clip | t | beat source | status | take | file |\n|---|---|---|---|---|---|")
    for l in v["lines"]:
        kept = next((t["file"] for t in reversed(l["takes"]) if t["status"] == "kept"), "")
        md.append(f"| {l['id']} | {l['t']} | {l['source'][:28]} | {l['status']} | {l['take']} | {kept} |")
        tot[l["status"]] = tot.get(l["status"], 0) + 1
md.insert(2, "Totals: " + ", ".join(f"{k} {n}" for k, n in sorted(tot.items())) + "\n")
(OUT / "index.md").write_text("\n".join(md) + "\n")
print(sum(tot.values()), "clips;", tot)
